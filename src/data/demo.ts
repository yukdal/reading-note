const USER_ID = 'demo-user';

function book(partial: Omit<Book, 'id' | 'user_id' | 'created_at' | 'updated_at'> & { created_at?: string }): Book {
  const created_at = partial.created_at ?? '2026-01-01T00:00:00.000Z';
  return {
    // 가짜 데이터라 새로고침마다 다시 만들어지지만, id는 고정해서 2단계 마인드맵
    // 캐시(브라우저 IndexedDB, 책 id 기준)가 새로고침 뒤에도 같은 책을 찾을 수 있게 한다.
    id: `demo-book-${partial.shelf_order}`,
    user_id: USER_ID,
    ...partial,
    created_at,
    updated_at: created_at,
  };
}

